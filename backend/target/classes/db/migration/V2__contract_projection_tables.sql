-- Kept as relational projections for future query optimization; the MVP currently stores
-- the canonical normalized document and rebuilds its flattened view during comparisons.
create table api_endpoint
(
    id           bigint generated by default as identity primary key,
    contract_id  bigint        not null references api_contract (id) on delete cascade,
    method       varchar(16)   not null,
    path         varchar(1024) not null,
    operation_id varchar(255)
);
create table api_field
(
    id          bigint generated by default as identity primary key,
    endpoint_id bigint        not null references api_endpoint (id) on delete cascade,
    json_path   varchar(1024) not null,
    field_name  varchar(255),
    data_type   varchar(128),
    required    boolean       not null default false,
    nullable    boolean       not null default false,
    location    varchar(64),
    parent_path varchar(1024)
);